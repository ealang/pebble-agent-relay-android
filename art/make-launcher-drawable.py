#!/usr/bin/env python3
"""Write the launcher drawables (foreground + monochrome) from the Pebble
Time 2 outline and the Telegram paper plane.

The body and screen polygons in art/pt2_outline.json were traced, in mm and
centred on the origin, from Core Devices' published dimension drawing
(github.com/coredevices/hardware, "Pebble 2 Duo and Pebble Time 2 -
dimensions.PDF"). This script scales them onto the 108-unit adaptive-icon
canvas, adds tapering straps and the plane, and writes

  app/src/main/res/drawable/ic_launcher_foreground.xml
  app/src/main/res/drawable/ic_launcher_monochrome.xml

Run from the repo root, then art/render-icons.py for the Pebble PNGs. No
dependencies beyond the standard library (the plane's enclosing circle is
read from render-icons.py's helper, which needs cairosvg + Pillow).
"""
import importlib.util, json, math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res/drawable"
OUTLINE = json.load(open(ROOT / "art/pt2_outline.json"))

BODY_W = 38          # body width in canvas units (108 = full icon, 66 = safe zone)
FACE = "screen"      # "screen" (window) or "glass" (bezel top surface)
PLANE_R = 12         # radius of the plane's minimal enclosing circle, canvas units
STRAP_MM = 22.1      # real strap width: it sits between the lug horns
STRAP_TAPER = 0.86   # strap end width / strap root width
SAFE_R = 33          # adaptive-icon safe circle radius

PLANE = ("M9.78,18.65L10.06,14.42L17.74,7.5C18.08,7.19 17.67,7.04 17.22,7.31L7.74,13.3L3.64,12C2.76,11.75 2.75,11.14 "
         "3.84,10.7L19.81,4.54C20.54,4.21 21.24,4.72 20.96,5.84L18.24,18.65C18.05,19.56 17.5,19.78 16.74,19.36L12.6,16.3"
         "L10.61,18.23C10.38,18.46 10.19,18.65 9.78,18.65Z")

spec = importlib.util.spec_from_file_location("ri", Path(__file__).with_name("render-icons.py"))
ri = importlib.util.module_from_spec(spec); spec.loader.exec_module(ri)


def extent(points, axis):
    vals = [p[axis] for p in points]
    return max(vals) - min(vals)


def poly_path(points, k):
    return "M" + "L".join(f"{54 + x * k:.2f},{54 + y * k:.2f}" for x, y in points) + "z"


def strap_path(k):
    w0 = STRAP_MM / 2 * k
    w1 = w0 * STRAP_TAPER
    y0 = max(p[1] for p in OUTLINE["body"]) * k * 0.9          # start under the horn tips
    y1 = math.floor(math.sqrt(SAFE_R ** 2 - w1 ** 2) * 10) / 10  # end inside the safe circle
    d = ""
    for sgn in (-1, 1):
        d += (f"M{54 - w0:.2f},{54 + sgn * y0:.2f}L{54 + w0:.2f},{54 + sgn * y0:.2f}"
              f"L{54 + w1:.2f},{54 + sgn * y1:.2f}L{54 - w1:.2f},{54 + sgn * y1:.2f}z")
    return d, y1


def main():
    k = BODY_W / extent(OUTLINE["body"], 0)
    cx, cy, r = ri.enclosing_circle(PLANE)
    s = PLANE_R / r
    tx, ty = 54 - cx * s, 54 - cy * s
    straps, strap_end = strap_path(k)
    body = poly_path(OUTLINE["body"], k)
    face = poly_path(OUTLINE[FACE], k)

    hdr = '<?xml version="1.0" encoding="utf-8"?>\n'
    vec = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    android:width="108dp"\n    android:height="108dp"\n'
           '    android:viewportWidth="108"\n    android:viewportHeight="108">\n')

    def path(fill, d, comment):
        return f'    <!-- {comment} -->\n    <path\n        android:fillColor="{fill}"\n        android:pathData="{d}" />\n'

    plane = (f'    <!-- paper plane: Material Design Icons "telegram" (Apache-2.0, see ui/AppIcons.kt),\n'
             f'         scaled so its minimal enclosing circle (r={PLANE_R}) is centred on the screen.\n'
             f'         Must stay the last path: render-icons.py reads it for the watch icons. -->\n'
             f'    <group\n        android:scaleX="{s:.4f}"\n        android:scaleY="{s:.4f}"\n'
             f'        android:translateX="{tx:.3f}"\n        android:translateY="{ty:.3f}">\n'
             f'        <path\n            android:fillColor="#FFFFFF"\n            android:pathData="{PLANE}" />\n    </group>\n')
    fg = (hdr + f"""<!--
  Launcher art: white Pebble Time 2 silhouette with a Telegram-blue screen
  carrying the same paper-plane glyph the Telegram tab uses. Navy background
  comes from @color/ic_launcher_background.

  Generated by art/make-launcher-drawable.py - edit that, not this. The body
  and screen outlines come from Core Devices' dimension drawing, scaled so
  the body is {BODY_W} units wide on the 108 canvas; the straps are the real
  22.1 mm, tapering, and end at y=54±{strap_end} just inside the 66-unit safe zone.
-->
""" + vec + path("#FFFFFF", straps, "straps")
          + path("#FFFFFF", body, "body (Pebble Time 2 outline incl. lug horns)")
          + path("#2AABEE", face, "screen") + plane + "</vector>\n")
    mono = (hdr + """<!--
  Themed-icon layer (Android 13+): launchers take only the alpha and tint it,
  so this is the foreground without the blue screen - watch plus plane in one
  colour. Geometry matches ic_launcher_foreground; same generator.
-->
""" + vec + path("#FFFFFF", straps, "straps") + path("#FFFFFF", body, "body") + plane + "</vector>\n")
    (RES / "ic_launcher_foreground.xml").write_text(fg)
    (RES / "ic_launcher_monochrome.xml").write_text(mono)
    print(f"plane scale {s:.4f}, strap end ±{strap_end}")


if __name__ == "__main__":
    main()
